// 04 Endless Stairwell (docs/liminal_maps/04-endless-stairwell.md).
//
// This is THE kind body (spec §3.3, §10). The world bakes it per (district,
// storey) with the tile ctx (spec §12.1): geometry.js generates the
// district's field of shafts (14–16 cores of varying placement, hand and door
// side), the storey's routed rungs and each landing's share of the storey;
// fragments.js generates each landing's small dead-end fragment inside its
// share from the parts catalogue (vestibule, lobby ring round the core with
// its rooms, stores, washrooms, plant rooms, office floors, car-park decks). A
// fragment's plan is keyed by its RUN (district, band, shaft, run), so a run's
// storeys are near-copies; the storey's own dice make the small differences.
// The editor kind (editor/kinds/stairwell.js) wraps it with
// FINITE_CTX_STAIRWELL: a 16-storey sample of two shafts on one chunk row
// whose landings open on fragments generated by the same grammar inside each
// shaft's chunk, three transfer corridors and lying plates.

const FLOORS = 16
const SALT = 0x04a1

// The finite kind's parameters (spec §12.1 "Reuse"): one ladder row (0), 16
// storeys, the kind's own three rungs and numbering, bricked fragments drawn
// as the kind draws them (an empty plan behind a walled door).
export const KIND_DEFAULTS = Object.freeze({ row: 0, floors: FLOORS, rungs: 'kind', numbering: 'kind', brickedAsMass: false })
export const FINITE_CTX_STAIRWELL = finiteCtx(KIND_DEFAULTS)
// The world's parameters: bricked fragments are mass behind the bricked
// door (never an enclosed pocket), rungs and plates come from geometry.js.
export const WORLD_PARAMS = Object.freeze({ row: null, floors: BAND, rungs: 'world', numbering: 'world', brickedAsMass: true })

// Label deviations (doc §4.5). Only shaft A may skip: a skip shifts every
// label above it, and shaft B keeps the count to the exit honest.
const LIES_A = ['skip', 'repeat', 'reversal', 'foreign', 'impossible']
const LIES_B = ['repeat', 'reversal', 'foreign', 'impossible']
const IMPOSSIBLE = ['-0', '9999', 'HErE', '    ']

// Authored lit tubes per chunk-storey: the world's (the fill pass tops a
// chunk up to its own cap, 8; the §11.1 gates are 12 per chunk-storey and 72
// within 60 u: measured worst 8 and 64 over seeds 1/5150/8086) and the kind
// lab's (no fill pass there; landing tubes come on top).
const LAMP_CAP = 7
const LAMP_CAP_KIND = 9

const STAIR_DIR = { E: STAIR_E, W: STAIR_W, S: STAIR_S, N: STAIR_N }
const SHAFT_NAMES = 'ABCDEFGHJKLMNPQR'

// A finite shaft in chunk (cx, cz): the core always spans local x 4..9 and
// its door sits at column 6, south of a core at rows 1..4 ('far') or north
// of one at rows 9..12 ('near').
function shaft(cx, west, near, cz = 0, baseCy = 0, topCy = FLOORS - 1) {
  const dir = west ? STAIR_W : STAIR_E
  const oz = cz * CHUNK
  const plan = stairwellPlan({ gx: cx * CHUNK + (west ? 8 : 5), gz: oz + (near ? 10 : 2), baseCy, topCy, dir, doorSide: near ? 'near' : 'far' })
  if (plan.error) return { error: plan.error }
  const door = stairwellDoor(plan)
  const sv = door.line === plan.core.z1 + 1 ? 1 : -1
  const col = cx * CHUNK + door.lx
  const line = oz + door.line
  const row = sv > 0 ? line : line - 1
  return {
    cx, cz, plan, sv, col, row, line,
    inside: { gx: col, gz: row - sv },
    back: sv > 0 ? 'S' : 'N',
    region: { x0: cx * CHUNK, z0: oz, x1: cx * CHUNK + CHUNK - 1, z1: oz + CHUNK - 1 },
  }
}

// A lamp budget: lamp(gx, gz, lit) plans a fixture unless it is lit and its
// chunk-storey already holds `cap` lit ones; returns whether it was planned.
// With `whole` (the kind lab), lamp.fits(cells) says whether lit tubes over
// all of `cells` would still fit (a class of identical rooms is lit whole or
// not at all: fragments.js lightRooms).
function lampBudget(plan, cap, counts = new Map(), whole = false) {
  const key = (gx, gz) => `${Math.floor(gx / CHUNK)},${Math.floor(gz / CHUNK)}`
  const lamp = (gx, gz, lit) => {
    const k = key(gx, gz)
    const n = counts.get(k) ?? 0
    if (lit && n >= cap) return false
    plan.lamp(gx, gz, lit)
    if (lit) counts.set(k, n + 1)
    return true
  }
  if (whole) lamp.fits = (cells) => {
    const need = new Map()
    for (const [gx, gz] of cells) need.set(key(gx, gz), (need.get(key(gx, gz)) ?? 0) + 1)
    for (const [k, n] of need) if ((counts.get(k) ?? 0) + n > cap) return false
    return true
  }
  return lamp
}

// The finite fragment (doc §4.2: inside the shaft's own chunk): the grammar
// in cells 0..12 of the chunk, off the core.
function finiteFragment(plan, S, kind, { seed, cy, s, run, dark, ids, jobs, lamp }) {
  const c = S.plan.globalCore
  const { x0, z0 } = S.region
  const G = new StoreyGrid({
    x0, z0, W: CHUNK, H: CHUNK,
    ok: (gx, gz) => gx - x0 <= CHUNK - 2 && gz - z0 <= CHUNK - 2 && !(gx >= c.x0 && gx <= c.x1 && gz >= c.z0 && gz <= c.z1),
  })
  // The run's dice (plan) and the storey's (the small differences).
  const r = rng(hash2i(seed, 9000 + s, run), SALT)
  const m = rng(hash2i(seed, cy, s), SALT)
  const style = runStyle(kind, rng(hash2i(seed, 7000 + s, run), SALT), rng(hash2i(seed, 7100, 0), SALT))
  const o = 10 + s
  G.take(o, S.col, S.row, true)
  plan.open(S.col, S.row, CELL_CORRIDOR)
  // The run's site (geometry.js fragmentSite), as in the world.
  const out = { x: S.col, z: S.row }
  const site = fragmentSite(kind, { out, n: [0, S.sv] }, rng(hash2i(seed, 7200 + s, run), SALT))
  return buildFragment({
    kind, G, plan, o,
    core: c,
    out,
    n: [0, S.sv],
    inClaim: () => true,
    site,
    box: { x0, z0, x1: x0 + CHUNK - 2, z1: z0 + CHUNK - 2 },
    r, m, style, ids, jobs, lamp,
    lit: (on) => on && !dark,
  })
}

// --- landing dressing ---------------------------------------------------------------

// The landing's loose pieces (doc §6: "chair on a landing"; bins and boxes
// stacked out of the way, a dead plant), on top of the standpipe. A
// landing's set is the run's (h: 2–3 pieces among chair, bin, boxes and
// plant, each on a hashed lobby cell against the far wall or an end wall);
// the storey's dice (m) take one away now and then. The landing frame:
// `inside` the cell inside the door, `along` the door wall's axis, `n` out
// through the door; cell (k, j) = inside + k·along − j·n, k −2..3, j 0..3.
const LANDING_KINDS = [FURN_CHAIR, PROP_WHEELIE_BIN, PROP_FLATPACK, FURN_PLANT]
const LANDING_SPOTS = [[-2, 3], [3, 3], [-1, 3], [2, 3], [0, 3], [1, 3], [-2, 2], [3, 2], [-2, 1], [3, 1]]
const WALL_OF = (v) => (v[0] === 1 ? 'E' : v[0] === -1 ? 'W' : v[1] === 1 ? 'S' : 'N')
function landingPieces(map, ly, { inside, along, n, core, h, m }) {
  const at = (k, j) => [inside.x + along[0] * k - n[0] * j, inside.z + along[1] * k - n[1] * j]
  const d = map.chunkAt(map.cellChunk(inside.x), ly, map.cellChunk(inside.z))
  // A piece blocks its cell (furniture is a column to the walk graph): it
  // goes only where every other walkable cell of the core stays reachable
  // from the door, so no landing, flight foot or exit is ever cut off.
  const walkable = (gx, gz) => gx >= core.x0 && gx <= core.x1 && gz >= core.z0 && gz <= core.z1 && cellWalkable(d, map.cellLocal(gx), map.cellLocal(gz))
  const open = (ax, az, bx, bz) => (ax !== bx ? map.wallVAt(Math.max(ax, bx), ly, az).wall !== 1 : map.wallHAt(ax, ly, Math.max(az, bz)).wall !== 1)
  const safe = ([bx, bz]) => {
    if (!walkable(inside.x, inside.z) || (bx === inside.x && bz === inside.z)) return false
    let total = 0
    for (let z = core.z0; z <= core.z1; z++) for (let x = core.x0; x <= core.x1; x++) if (walkable(x, z) && !(x === bx && z === bz)) total++
    const seen = new Set([`${inside.x},${inside.z}`])
    const queue = [[inside.x, inside.z]]
    for (let i = 0; i < queue.length; i++) {
      const [x, z] = queue[i]
      for (const [dx, dz] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
        const nx = x + dx
        const nz = z + dz
        const k = `${nx},${nz}`
        if (seen.has(k) || (nx === bx && nz === bz) || !walkable(nx, nz) || !open(x, z, nx, nz)) continue
        seen.add(k)
        queue.push([nx, nz])
      }
    }
    return queue.length === total
  }
  // Never on a flight's landing or exit cell, a hole, or a cell holding a piece.
  const busy = new Set()
  for (const st of [d.stairUp, d.stairDown]) {
    if (!st) continue
    for (const c of [st.landing, st.exit, ...st.run]) busy.add(`${c.lx},${c.lz}`)
  }
  for (const f of d.furniture) busy.add(`${f.lx},${f.lz}`)
  const ok = ([gx, gz]) => {
    const lx = map.cellLocal(gx)
    const lz = map.cellLocal(gz)
    return map.cellAt(gx, ly, gz).kind === CELL_LOBBY && !busy.has(`${lx},${lz}`) && !d.hasFloorHole(lx, lz) && !d.hasCeilHole(lx, lz)
  }
  const kinds = [...LANDING_KINDS]
  for (let i = kinds.length - 1; i > 0; i--) {
    const j = h(30 + i) % (i + 1)
    ;[kinds[i], kinds[j]] = [kinds[j], kinds[i]]
  }
  const spots = [...LANDING_SPOTS]
  for (let i = spots.length - 1; i > 0; i--) {
    const j = h(50 + i) % (i + 1)
    ;[spots[i], spots[j]] = [spots[j], spots[i]]
  }
  const want = 2 + (h(1) % 2)
  const gone = m(1) % 5 === 0 ? m(2) % want : -1
  let placed = 0
  for (const [k, j] of spots) {
    if (placed >= want) break
    const c = at(k, j)
    if (!ok(c) || !safe(c)) continue
    const kind = kinds[placed]
    placed++
    if (placed - 1 === gone) continue
    const wall = j === 3 ? WALL_OF([-n[0], -n[1]]) : WALL_OF(k < 0 ? [-along[0], -along[1]] : along)
    addPiece(map, ly, { gx: c[0], gz: c[1], kind, wall, front: WALL_TO_FRONT[wall] })
    busy.add(`${map.cellLocal(c[0])},${map.cellLocal(c[1])}`)
  }
}

// --- transfer corridor ---------------------------------------------------------------

// One rung of the ladder: a 2-wide corridor from shaft A's door to shaft
// B's along rows 6..7 (between every core and its door cell), with a jog
// through the chunks between them, fire doors near both shafts and a few
// closets. `ctx.lamp(on, gx)` darkens the half of the corridor nearest a
// shaft whose breaker segment holds this storey. Returns a note.
function transfer(plan, A, B, ctx, t) {
  const { r, ids } = ctx
  const lane = (x0, x1, z) => plan.rect({ x0, x1, z0: z, z1: z + 1 }, CELL_CORRIDOR)
  plan.open(A.col, A.row)
  plan.open(B.col, B.row)
  const jog = r(t, 50) % 3 // 0 straight, 1 north, 2 south
  const xa = (A.cx + 1) * CHUNK + 2
  const xb = B.cx * CHUNK - 4
  let note = 'straight'
  if (jog === 0 || xb - xa < 3) lane(A.col, B.col, 6)
  else {
    const jz = jog === 1 ? 2 : 10
    lane(A.col, xa + 1, 6)
    plan.rect({ x0: xa, x1: xa + 1, z0: Math.min(6, jz), z1: Math.max(7, jz + 1) }, CELL_CORRIDOR)
    lane(xa, xb + 1, jz)
    plan.rect({ x0: xb, x1: xb + 1, z0: Math.min(6, jz), z1: Math.max(7, jz + 1) }, CELL_CORRIDOR)
    lane(xb, B.col, 6)
    note = jog === 1 ? 'jogs north' : 'jogs south'
  }
  // Double fire doors three cells out of each shaft.
  for (const gx of [A.col + 3, B.col - 2]) {
    plan.edge('v', gx, 6, 0, PASSAGE_DOOR)
    plan.edge('v', gx, 7, 0, PASSAGE_DOOR)
  }
  // Closets off the lane, in the chunks between the shafts: each sits on
  // the lane's north or south flank, whichever rows the lane holds there.
  for (let cx = A.cx + 1; cx < B.cx; cx++) {
    for (const lx of [5, 9]) {
      const gx = cx * CHUNK + lx
      const key = t * 16 + cx
      if (r(key, 51 + lx) % 2) continue
      const top = [6, 2, 10].find((z) => plan.has(gx, z) && plan.has(gx, z + 1))
      if (top === undefined) continue
      const north = r(key, 52 + lx) % 2 === 0
      const z = north ? top - 1 : top + 2
      if (plan.has(gx, z)) continue
      plan.room({ x0: gx, x1: gx, z0: z, z1: z }, {
        spaceId: ids.next++, role: SPACE_ROLE_STORAGE,
        doors: [{ axis: 'h', gx, gz: north ? top : top + 2 }],
      })
    }
  }
  for (let gx = A.col + 1; gx < B.col; gx += 3) {
    const gz = plan.has(gx, 6) ? 6 : plan.has(gx, 2) ? 2 : 10
    if (plan.has(gx, gz)) plan.lamp(gx, gz, ctx.lamp(true, gx))
  }
  return note
}

// --- numbering -------------------------------------------------------------------------

// Labels per storey for one shaft: the shaft's own count (storey + offset)
// with one deviation per 8-storey band, never on the bottom storey (shaft
// B's exit) or the top three (the baseline the visitor sees first).
function numbering(r, s, offset, kinds) {
  const count = Array.from({ length: FLOORS }, (_, cy) => cy + offset)
  const labels = count.map(String)
  const lies = []
  for (let band = 0; band < FLOORS / 8; band++) {
    const lo = Math.max(1, band * 8)
    const hi = Math.min(FLOORS - 4, band * 8 + 7)
    const key = s * 8 + band
    const kind = kinds[r(key, 60) % kinds.length]
    const cy = lo + (r(key, 61) % (hi - lo + (kind === 'reversal' ? 0 : 1)))
    const n = count[cy]
    if (kind === 'skip') {
      // The count jumps by two here and stays shifted above.
      for (let k = cy; k < FLOORS; k++) labels[k] = String(++count[k])
    } else if (kind === 'repeat') labels[cy] = String(count[cy - 1])
    else if (kind === 'reversal') [labels[cy], labels[cy + 1]] = [String(count[cy + 1]), String(count[cy])]
    else if (kind === 'foreign') labels[cy] = [`b${n}`, `${n}F`, `${n - 1}A`][r(key, 62) % 3]
    else labels[cy] = IMPOSSIBLE[r(key, 63) % IMPOSSIBLE.length]
    lies.push({ cy, kind, label: labels[cy] })
  }
  return { labels, lies }
}

// --- build (finite: the kind lab's 16-storey sample) -----------------------------------

function buildStairwell(map, seed, ctx) {
  const r = rng(seed, SALT)
  const row = ctx.params?.row ?? 0
  // Shaft A in chunk 0; shaft B 2–4 chunks east. Each picks its own flight
  // hand and door side, so the two shafts never quite match.
  const A = shaft(0, r(1, 1) % 2 === 1, false, row)
  const B = shaft(2 + (r(1, 2) % 3), r(1, 3) % 2 === 1, r(1, 4) % 2 === 1, row)
  if (A.error || B.error) return { error: `stairwell: ${A.error ?? B.error}` }
  const shafts = [A, B]

  // Three rungs, 4–6 storeys apart, clear of the top and bottom storeys.
  const t1 = 2 + (r(2, 1) % 3)
  const t2 = t1 + 4 + (r(2, 2) % 3)
  const t3 = Math.min(FLOORS - 2, t2 + 4 + (r(2, 3) % 3))
  const rungs = [t1, t2, t3]

  // Breaker segments: one block of 3–4 dark storeys per shaft (landings,
  // fragments, and the shaft's half of a rung corridor), below the
  // visitor's first three landings (the world's run 3–7 over its 16-storey
  // bands; the kind's sample keeps them short so a lit floor stays the rule).
  const darkLen = shafts.map((_, s) => 3 + (r(4, s) % 3))
  const darkFrom = shafts.map((_, s) => 1 + (r(3, s) % (FLOORS - 3 - darkLen[s])))
  const segmentDark = (s, cy) => cy >= darkFrom[s] && cy < darkFrom[s] + darkLen[s]

  // Fragment runs per shaft ({ kind, run }: the run keys its style).
  const runs = shafts.map((_, s) => fragmentRuns(r, s, FLOORS))
  // Spawn (A's top) and exit (B's bottom) storeys keep their fire doors.
  for (const [s, cy] of [[0, FLOORS - 1], [1, 0]]) if (runs[s][cy].kind === 'bricked') runs[s][cy] = { kind: 'corridor', run: -1 }

  const ids = { next: 4096 }
  const jobs = []
  const fragmentNotes = shafts.map(() => [])
  const bricked = []
  const rungNotes = []
  const layouts = []
  for (let cy = 0; cy < FLOORS; cy++) {
    const storeyJobs = { rooms: [], pieces: [] }
    jobs.push(storeyJobs)
    if (rungs.includes(cy)) {
      const plan = new FloorPlan({ x0: 0, z0: 0, x1: B.cx * CHUNK + CHUNK - 1, z1: CHUNK - 1 })
      const mid = (A.col + B.col) / 2
      const rctx = { r, ids, lamp: (on, gx) => on && !segmentDark(gx < mid ? 0 : 1, cy) }
      const note = transfer(plan, A, B, rctx, cy)
      fragmentNotes[0].push(`${cy}:transfer`)
      fragmentNotes[1].push(`${cy}:transfer`)
      plan.compile(map, cy)
      rungNotes.push(`storey ${cy + 1}: transfer corridor ${B.col - A.col} cells, ${note}`)
      continue
    }
    shafts.forEach((S, s) => {
      const plan = new FloorPlan(S.region)
      let { kind, run } = runs[s][cy]
      let dark = segmentDark(s, cy)
      if (kind === 'dark') {
        // A dark run copies the geometry (and style) it interrupts.
        let k = cy
        while (k >= 0 && (runs[s][k].kind === 'dark' || runs[s][k].kind === 'bricked')) k--
        ;({ kind, run } = k >= 0 ? runs[s][k] : { kind: 'corridor', run: -1 })
        dark = true
      }
      if (kind === 'bricked') {
        bricked.push({ s, cy })
        fragmentNotes[s].push(`${cy}:bricked`)
      } else {
        const lamp = lampBudget(plan, LAMP_CAP_KIND, new Map(), true)
        const note = finiteFragment(plan, S, kind, { seed, cy, s, run, dark, ids, jobs: storeyJobs, lamp })
        fragmentNotes[s].push(`${cy}:${dark ? 'dark ' : ''}${kind}`)
        layouts.push(`storey ${cy + 1} ${s ? 'B' : 'A'}: ${note}`)
      }
      plan.compile(map, cy)
    })
  }

  for (const S of shafts) ctx.kit.stairwell(map, S.plan, { enclosed: true })

  // Touch-ups: bricked doors, landing lamps, numbers, the exit.
  for (const { s, cy } of bricked) map.setWallH(shafts[s].col, cy, shafts[s].line, 1, PASSAGE_WALL)
  shafts.forEach((S, s) => {
    for (let cy = 0; cy < FLOORS; cy++) {
      // One tube inside the door and one at the core's far end; dark
      // segments kill both.
      const lit = !segmentDark(s, cy)
      const d = map.chunkAt(S.cx, cy, S.cz)
      for (const [gx, gz] of [[S.inside.gx, S.inside.gz], [S.inside.gx + 3, S.inside.gz - S.sv * 3]]) {
        if (!d.hasCeilHole(map.cellLocal(gx), map.cellLocal(gz))) map.setLamp(gx, cy, gz, lit)
      }
    }
  })
  const offsetA = 9 + (r(5, 1) % 12)
  const numbers = [numbering(r, 0, offsetA, LIES_A), numbering(r, 1, 1, LIES_B)]
  shafts.forEach((S, s) => {
    for (let cy = 0; cy < FLOORS; cy++) labelFloor(map, cy, numbers[s].labels[cy], { cx: S.cx, cz: S.cz })
  })
  const exit = { gx: B.col, gz: B.row, cy: 0 }
  markExit(map, ctx, exit)

  // Furniture last: furnished rooms, then the placed pieces, then a
  // standpipe on every landing (the door wall's corner cell, which leaves
  // the landing ring a path).
  for (let cy = 0; cy < FLOORS; cy++) {
    for (const room of jobs[cy].rooms) createRoom(map, { cy, ...room, lamp: false })
    for (const p of jobs[cy].pieces) addPiece(map, cy, { ...p, front: p.front ?? WALL_TO_FRONT[p.wall] })
    shafts.forEach((S, s) => {
      addPiece(map, cy, { gx: S.inside.gx + 3, gz: S.inside.gz, kind: PROP_STANDPIPE, wall: S.back, front: WALL_TO_FRONT[S.back] })
      const run = runs[s][cy].run
      landingPieces(map, cy, {
        inside: { x: S.inside.gx, z: S.inside.gz }, along: [1, 0], n: [0, S.sv], core: S.plan.globalCore,
        h: rng(hash2i(seed, 7300 + s, run), SALT), m: rng(hash2i(seed, cy, 7400 + s), SALT),
      })
    })
  }

  const lieNote = (name, { lies }) => `shaft ${name} lies: ${lies.map((l) => `storey ${l.cy + 1} ${l.kind} ("${l.label.trim() || 'blank'}")`).join(', ')}`
  return {
    spawn: { gx: A.inside.gx, gz: A.inside.gz, cy: FLOORS - 1 },
    exit,
    notes: [
      `two shafts ${B.cx} chunks apart, ${FLOORS} storeys; spawn on shaft A's top landing, exit at shaft B's foot`,
      ...rungNotes,
      `plates: shaft A reads ${offsetA}+, shaft B (honest to the exit) reads 1+`,
      lieNote('A', numbers[0]),
      lieNote('B', numbers[1]),
      `dark segments: A storeys ${darkFrom[0] + 1}-${darkFrom[0] + darkLen[0]}, B storeys ${darkFrom[1] + 1}-${darkFrom[1] + darkLen[1]}`,
      `fragments A: ${fragmentNotes[0].join(' ')}`,
      `fragments B: ${fragmentNotes[1].join(' ')}`,
      ...layouts,
      'fragments are generated from the parts catalogue (vestibule, corridor floors, open-plan floors, plant halls, car-park decks); a run keeps its plan, each storey changes a detail',
      'floorPockets: off the three rungs each storey is two pockets joined only by the stairs',
      'look at: the same landing (door, standpipe, plate) storey after storey, the plate that is wrong, the wedge in a closet door, the long rung corridors',
      'stand-ins: closed 6×4 switchback core (no open well to look down), a plain wall for the bricked door, LEVEL plates for painted numbers (none on a core\'s top storey), standpipe and wedge draw as boxes until the stairwell pack GLBs load; no lift, self-closing doors, emergency light or well acoustics',
    ],
  }
}

// --- build (world: one storey of one district) -----------------------------------------

// A double fire door across a 2-wide corridor at path step k, where the path
// runs straight through k − 1..k + 1 and the corridor is exactly two cells
// wide across the door line (so the leaves close it).
function fireDoor(plan, isCorr, path, k) {
  if (k < 1 || k + 1 >= path.length) return false
  const [ax, az] = path[k - 1]
  const [bx, bz] = path[k]
  const [cx, cz] = path[k + 1]
  if (bx - ax !== cx - bx || bz - az !== cz - bz) return false
  if (bx !== ax) {
    const gx = Math.max(ax, bx) + 1
    if (isCorr(gx - 1, bz - 1) || isCorr(gx, bz - 1) || isCorr(gx - 1, bz + 2) || isCorr(gx, bz + 2)) return false
    plan.edge('v', gx, bz, 0, PASSAGE_DOOR)
    plan.edge('v', gx, bz + 1, 0, PASSAGE_DOOR)
  } else {
    const gz = Math.max(az, bz) + 1
    if (isCorr(bx - 1, gz - 1) || isCorr(bx - 1, gz) || isCorr(bx + 2, gz - 1) || isCorr(bx + 2, gz)) return false
    plan.edge('h', bx, gz, 0, PASSAGE_DOOR)
    plan.edge('h', bx + 1, gz, 0, PASSAGE_DOOR)
  }
  return true
}

// One storey of one district (tile mode, spec §12.1). Kind-local storey 0 is
// GLOBAL storey ctx.cy0; local cells are tile-local (0..55).
function buildStairwellStorey(map, ctx) {
  const { worldSeed, key } = ctx
  const cy = ctx.cy0
  const ly = 0 // kind-local storey of the bake
  const P = storeyPlan(worldSeed, key.tx, key.tz, cy)
  const L = P.layout
  const home = key.tx === 0 && key.tz === 0
  const G = exitStorey(worldSeed)

  // Global flight parity: flight(lowerCy) is the even or odd lane by the
  // parity of lowerCy, whatever bake stamps it (spec §12.1 "Flights").
  const baseLy = -1 - ((cy - 1) & 1)
  const cores = []
  for (const S of L.shafts) {
    const plan = stairwellPlan({ gx: S.planGx, gz: S.planGz, baseCy: baseLy, topCy: ly + 1, dir: STAIR_DIR[S.dir], doorSide: S.far ? 'far' : 'near' })
    if (plan.error) return { error: `stairwell: ${plan.error}` }
    cores.push(plan)
  }

  // The storey's buildable cells: kept chunks, off the cores, and off a
  // chunk's east column / south row where it faces a solid chunk or the
  // district edge (§6.8 rule 1), except at this storey's port cells.
  const kept = (ix, iz) => ix >= 0 && iz >= 0 && ix < DISTRICT && iz < DISTRICT && ((P.mask >> (ix + DISTRICT * iz)) & 1) === 1
  const port = new Set((P.ext?.cells ?? []).map(([x, z]) => `${x},${z}`))
  const grid = new StoreyGrid({
    x0: 0, z0: 0, W: SPAN, H: SPAN,
    ok: (gx, gz) => {
      const ix = Math.floor(gx / CHUNK)
      const iz = Math.floor(gz / CHUNK)
      if (!kept(ix, iz) || L.core[gz * SPAN + gx]) return false
      if (port.has(`${gx},${gz}`)) return true
      if (gx % CHUNK === CHUNK - 1 && !kept(ix + 1, iz)) return false
      if (gz % CHUNK === CHUNK - 1 && !kept(ix, iz + 1)) return false
      return true
    },
  })
  const plan = new FloorPlan({ x0: 0, z0: 0, x1: SPAN - 1, z1: SPAN - 1 })
  const counts = new Map()
  // The landing tubes (two per core) come out of each shaft chunk's budget.
  for (const S of L.shafts) counts.set(`${S.ix},${S.iz}`, 2)
  const lamp = lampBudget(plan, LAMP_CAP, counts)
  const ids = { next: 4096 }
  const jobs = { rooms: [], pieces: [] }
  const notes = []
  const segDark = P.segDark
  // The building's dice (fragments.js runStyle): one module per kind in the band.
  const building = dice(bandSeed(worldSeed, key.tx, key.tz, P.band), 0x5716)

  // Rungs: the routed corridors (owner 1), fire doors near the shafts they
  // leave, stores and the odd room off their flanks, tubes along them.
  if (P.corridors) {
    const CORR = 1
    const cells = []
    for (let gz = 0; gz < SPAN; gz++) {
      for (let gx = 0; gx < SPAN; gx++) {
        if (!P.corridors.cells[gz * SPAN + gx]) continue
        grid.take(CORR, gx, gz, true)
        plan.open(gx, gz, CELL_CORRIDOR)
        cells.push([gx, gz])
      }
    }
    const isCorr = (gx, gz) => grid.isCorr(CORR, gx, gz)
    const rc = rng(ctx.planSeed, SALT + 1)
    for (const p of P.corridors.paths) {
      const rung = typeof p.to === 'number'
      const ends = [3]
      if (rung) ends.push(p.blocks.length - 4)
      for (const k of ends) for (let j = 0; j < 4 && !fireDoor(plan, isCorr, p.blocks, k + j); j++);
      // Tubes every third step; a rung's halves go dark with the breaker
      // segment of the shaft they lead to.
      const near = (i) => (rung && i >= p.blocks.length / 2 ? p.to : p.from)
      for (let i = 1; i < p.blocks.length; i += 3) {
        const [bx, bz] = p.blocks[i]
        lamp(bx, bz, !segDark[near(i)])
      }
      notes.push(`storey ${cy}: ${rung ? `transfer ${SHAFT_NAMES[p.from]}-${SHAFT_NAMES[p.to]}` : `long rung ${p.to}`} (${p.blocks.length} steps)`)
    }
    // Side rooms off the corridors, in the own chunks and territories of the
    // shafts on them (never into another landing's approach).
    let mine = 0
    for (const s of P.onCorridor) mine |= 1 << s
    const inClaim = (gx, gz) => {
      const s = P.owner[gz * SPAN + gx]
      return s >= 0 && ((mine >> s) & 1) === 1
    }
    const wingDark = P.onCorridor.some((s) => segDark[s])
    const style = runStyle('wing', dice((bandSeed(worldSeed, key.tx, key.tz, P.band) + Math.imul(cy, 31)) >>> 0, 0x5718), building)
    // Two to four doors per rung (doc §4.3: "a few doors"), off its own cells.
    let n = 0
    for (const [k, p] of P.corridors.paths.entries()) {
      const own = []
      const seen = new Set()
      for (const [bx, bz] of p.blocks) {
        for (const [gx, gz] of [[bx, bz], [bx + 1, bz], [bx, bz + 1], [bx + 1, bz + 1]]) {
          const id = gz * SPAN + gx
          if (seen.has(id) || !isCorr(gx, gz)) continue
          seen.add(id)
          own.push([gx, gz])
        }
      }
      // Each end's rooms in that end's share: a few doors near each landing.
      const ends = typeof p.to === 'number' ? [p.from, p.to] : [p.from]
      for (const s of ends) {
        const rk = dice((ctx.planSeed + Math.imul(k + 1, 0x9e3779b1) + Math.imul(s + 1, 0x85ebca6b)) >>> 0, 0x5719)
        const mineS = (gx, gz) => inClaim(gx, gz) && P.owner[gz * SPAN + gx] === s
        n += rungWings({ G: grid, plan, o: CORR, from: own, r: rk, m: rc, style, ids, jobs, lamp, lit: (on) => on && !wingDark, inClaim: mineS })
      }
    }
    notes.push(`storey ${cy}: ${n} rooms off the rungs`)
  }

  // Every other landing's fragment, in its claim.
  const bricked = []
  for (const fr of P.frags) {
    if (fr.kind === 'bricked') continue
    const S = L.shafts[fr.s]
    grid.take(10 + fr.s, S.out.x, S.out.z, true)
    plan.open(S.out.x, S.out.z, CELL_CORRIDOR)
  }
  P.frags.forEach((fr, i) => {
    const S = L.shafts[fr.s]
    if (fr.kind === 'bricked') {
      bricked.push(S)
      return
    }
    const chunks = P.claims[i].map((c) => [c % DISTRICT, Math.floor(c / DISTRICT)])
    // The landing's domain (geometry.js domains): its share of the storey,
    // off every other landing's approach and every core.
    const inClaim = (gx, gz) => P.owner[gz * SPAN + gx] === S.s
    const box = {
      x0: Math.min(...chunks.map(([ix]) => ix)) * CHUNK,
      z0: Math.min(...chunks.map(([, iz]) => iz)) * CHUNK,
      x1: Math.max(...chunks.map(([ix]) => ix)) * CHUNK + CHUNK - 1,
      z1: Math.max(...chunks.map(([, iz]) => iz)) * CHUNK + CHUNK - 1,
    }
    // The run's dice (claim, module, plan: the same on every storey of the
    // run) and the storey's (the small differences).
    const runSeed = (bandSeed(worldSeed, key.tx, key.tz, P.band) + Math.imul(fr.s + 1, 7919) + Math.imul(fr.run + 1, 104729)) >>> 0
    const r = dice(runSeed, 0x51a1)
    const m = rng(hash2i(ctx.planSeed, fr.s, 0x51a1), SALT)
    const style = runStyle(fr.kind, dice(runSeed, 0x5717), building)
    // Round the spawn (district (0,0), storeys −1..1) every run is a lit
    // one: the run starts among lit rooms (geometry.js keeps its tubes too).
    if (home && cy >= -1 && cy <= 1) style.lit = true
    const dark = fr.dark || segDark[fr.s]
    const note = buildFragment({
      kind: fr.kind, G: grid, plan, o: 10 + fr.s,
      core: S.core,
      out: S.out, n: S.n, inClaim, box, site: P.sites[fr.s],
      r, m, style, ids, jobs, lamp,
      lit: (on) => on && !dark,
    })
    notes.push(`storey ${cy}: shaft ${SHAFT_NAMES[fr.s]} ${dark ? 'dark ' : ''}${note}`)
  })

  plan.compile(map, ly)
  // The district's owned seam lines open at their ports (§6.8 rule 3).
  openOwnedSeam(map, ctx, ly, 'west')
  openOwnedSeam(map, ctx, ly, 'north')

  for (const core of cores) ctx.kit.stairwell(map, core, { enclosed: true })
  // brickedAsMass (WORLD_PARAMS): nothing was planned outside the door, so
  // the fragment is mass behind the walled door.
  for (const S of bricked) {
    if (S.door.axis === 'h') map.setWallH(S.door.at, ly, S.door.line, 1, PASSAGE_WALL)
    else map.setWallV(S.door.line, ly, S.door.at, 1, PASSAGE_WALL)
  }

  const anomalies = L.shafts.map((S) => {
    const a = anomalyAt(worldSeed, key.tx, key.tz, S.s, cy)
    return a && a.cy === cy ? a.kind : null
  })
  const step = (S, k, j = 0) => ({ x: S.inside.x + S.along[0] * k - S.n[0] * j, z: S.inside.z + S.along[1] * k - S.n[1] * j })
  for (const S of L.shafts) {
    // Landing tubes: dead in a breaker segment; the 'dead-landing' anomaly
    // inverts the storey (a dead landing among lit ones, or one lit tube
    // in a dead segment).
    const lit = !segDark[S.s] !== (anomalies[S.s] === 'dead-landing')
    const d = map.chunkAt(S.ix, ly, S.iz)
    for (const c of [S.inside, step(S, 3, 3)]) {
      if (!d.hasCeilHole(map.cellLocal(c.x), map.cellLocal(c.z))) map.setLamp(c.x, ly, c.z, lit)
    }
    labelFloor(map, ly, labelAt(worldSeed, key.tx, key.tz, S.s, cy), { cx: S.ix, cz: S.iz })
    if (anomalies[S.s]) notes.push(`storey ${cy}: shaft ${SHAFT_NAMES[S.s]} ${anomalies[S.s]}`)
  }

  if (home && cy === G) {
    // Exit candidates (§8.2): B's landing outside its fire door, then inside it.
    markExit(map, ctx, { gx: L.B.out.x, gz: L.B.out.z, cy: ly })
    markExit(map, ctx, { gx: L.B.inside.x, gz: L.B.inside.z, cy: ly })
  }
  if (home && cy === 0) markSpawn(map, ctx, { gx: L.A.inside.x, gz: L.A.inside.z, cy: ly })

  for (const room of jobs.rooms) createRoom(map, { cy: ly, ...room, lamp: false })
  for (const p of jobs.pieces) addPiece(map, ly, { ...p, front: p.front ?? WALL_TO_FRONT[p.wall] })
  for (const S of L.shafts) {
    if (anomalies[S.s] === 'no-standpipe') continue
    const front = WALL_TO_FRONT[S.wall]
    const a = step(S, 3)
    addPiece(map, ly, { gx: a.x, gz: a.z, kind: PROP_STANDPIPE, wall: S.wall, front })
    if (anomalies[S.s] === 'two-standpipes') {
      const b = step(S, -2)
      addPiece(map, ly, { gx: b.x, gz: b.z, kind: PROP_STANDPIPE, wall: S.wall, front })
    }
  }
  // The landings' loose pieces: the run's set (a landing on a rung corridor
  // keeps the storey's), the storey's small differences.
  for (const S of L.shafts) {
    const fr = P.frags.find((f) => f.s === S.s)
    const run = fr ? fr.run : 4096 + cy
    const h = dice((bandSeed(worldSeed, key.tx, key.tz, P.band) + Math.imul(S.s + 1, 7919) + Math.imul(run + 1, 104729)) >>> 0, 0x1a4d)
    landingPieces(map, ly, {
      inside: S.inside, along: S.along, n: S.n, core: S.core,
      h, m: rng(hash2i(ctx.planSeed, S.s, 0x1a4d), SALT),
    })
  }
  ctx.notes?.push?.(...notes)
  return {}
}

// The tile program (spec §3.3): build<Id>Tile(map, seed, ctx). Finite ctx →
// the kind lab's map; tile ctx → one storey of one district.
export function buildStairwellTile(map, seed, ctx = FINITE_CTX_STAIRWELL) {
  if (ctx.mode === 'tile') return buildStairwellStorey(map, ctx)
  return buildStairwell(map, seed, ctx)
}
